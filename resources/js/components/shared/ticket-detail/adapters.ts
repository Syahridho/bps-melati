import { InputDataTicketDetail } from '@/types/input-data';
import { ShowProps as LaporanSelesaiShowProps } from '@/types/laporan-selesai';
import { TicketDetail } from '@/types/laporan-masuk';
import { TicketDetailData } from './types';

export function mapLaporanMasukToDetailData(ticket: TicketDetail): TicketDetailData {
    return {
        id: ticket.id,
        ticket_number: ticket.ticket_number,
        period: ticket.period,
        sequence: ticket.sequence,
        classification: ticket.classification,
        title: ticket.title,
        service_type: ticket.service_type,
        satuan_tugas: ticket.satuan_tugas,
        reporter_name: ticket.reporter_name,
        reporter_email: ticket.reporter_email,
        reporter_wa: ticket.reporter_wa,
        content: ticket.content,
        status: ticket.status,
        version: ticket.version,
        is_read: ticket.is_read,
        source_app: ticket.source_app,
        channel: ticket.channel,
        created_by_name: ticket.created_by_name,
        completed_at: ticket.completed_at,
        closed_reason: ticket.closed_reason,
        is_pengawasan: ticket.is_pengawasan,
        pengawasan_at: ticket.pengawasan_at,
        pengawasan_by_name: ticket.pengawasan_by_name,
        is_flagged: ticket.is_flagged,
        flagged_at: ticket.flagged_at,
        flagged_by_name: ticket.flagged_by_name,
        flag_note: ticket.flag_note,
        kadar_pengawasan_days: ticket.kadar_pengawasan_days,
        classification_default_days: ticket.classification_default_days,
        auto_close_at: ticket.auto_close_at,
        created_at: ticket.created_at,
        updated_at: ticket.updated_at,
        attachments: (ticket.attachments ?? []).map((att) => ({
            id: att.id,
            original_name: att.original_name,
            mime_type: att.mime_type,
            size: att.size,
            url: att.url,
        })),
        responses: (ticket.responses ?? []).map((resp) => ({
            id: resp.id,
            type: resp.type,
            message: resp.message,
            user_name: resp.user_name,
            is_reporter: resp.is_reporter,
            is_system: resp.is_system,
            sent_at: resp.sent_at,
            created_at: resp.created_at,
            email_status: resp.email_status,
            email_sent_at: resp.email_sent_at,
            email_failed_at: resp.email_failed_at,
            email_error: resp.email_error,
            attachments: (resp.attachments ?? []).map((att) => ({
                id: att.id,
                original_name: att.original_name,
                mime_type: att.mime_type,
                size: att.size,
                url: att.url,
            })),
        })),
    };
}

